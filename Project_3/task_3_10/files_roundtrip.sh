#!/bin/bash

echo "========================================="
echo "    СОЗДАНИЕ И УДАЛЕНИЕ ФАЙЛОВ"
echo "========================================="
echo ""

echo "Этап 1: Создание файлов тест 1 тест 2 ну и далее до 10 короче ... "
echo "-------------------------------------------------"

for i in {1..10}; do
    touch "test$i.txt"
    echo "Создан файлик: test$i.txt"
done

echo ""
echo "Список созданных файликов:"
ls -la test*.txt
echo ""

echo "Этап 2: Удаление файликов тест1 тест2 ну крч и так далее...."
echo "-------------------------------------------------"

counter=10
while [ $counter -ge 1 ]; do
    rm "test$counter.txt"
    echo "Удален файлик: test$counter.txt"
    ((counter--))
done

echo ""
echo "Проверка: файлики удалены"
ls test*.txt 2>/dev/null || echo "Все файлики удалены. Папка пуста."
echo ""
echo "Программа завершена."
