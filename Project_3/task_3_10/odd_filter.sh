#!/bin/bash

echo "Нечетные числа от 1 до 20 (остановка на 15):"
echo "============================================"

for i in {1..20}; do
    if [ $i -eq 15 ]; then
        echo "Число 15 :3333333333333 стоп ^_^"
        break
    fi
    
    if [ $((i % 2)) -eq 0 ]; then
        continue
    fi
    
    echo "Нечетное число: $i"
done

echo "Пррграмма завершена."

